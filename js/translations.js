// === Translation application ===
/**
 * Apply translations to all elements with data-translate, data-value and data-placeholder attributes.
 * Elements with data-translate will have their textContent updated.
 * Elements with data-value will have their value property updated.
 * Elements with data-placeholder will have their placeholder updated.
 */
function applyTranslations() {
    const lang = getUserLanguage();
    // Set document language attribute
    document.documentElement.lang = lang;
    // Translate text content
    const textEls = document.querySelectorAll('[data-translate]');
    textEls.forEach(el => {
        const key = el.dataset.translate;
        const translation = translations[lang] && translations[lang][key];
        if (translation) {
            el.textContent = translation;
        }
    });
    // Translate input/select values
    const valueEls = document.querySelectorAll('[data-value]');
    valueEls.forEach(el => {
        const key = el.dataset.value;
        const translation = translations[lang] && translations[lang][key];
        if (translation) {
            el.value = translation;
        }
    });
    // Translate placeholders
    const placeholderEls = document.querySelectorAll('[data-placeholder]');
    placeholderEls.forEach(el => {
        const key = el.dataset.placeholder;
        const translation = translations[lang] && translations[lang][key];
        if (translation) {
            el.placeholder = translation;
        }
    });
}

// Automatically apply translations when the DOM is fully loaded
document.addEventListener('DOMContentLoaded', function () {
    applyTranslations();
});

// Language management functions
function getUserLanguage() {
    // Try to read language from current logged in user
    const user = JSON.parse(localStorage.getItem('currentUser'));
    if (user && user.language) {
        return user.language;
    }
    // Fallback to a selected language stored before login
    const selected = localStorage.getItem('selectedLanguage');
    return selected || 'bs';
}

function setUserLanguage(lang) {
    const user = JSON.parse(localStorage.getItem('currentUser'));
    if (user) {
        user.language = lang;
        localStorage.setItem('currentUser', JSON.stringify(user));
        // Update in users array
        const users = JSON.parse(localStorage.getItem('users')) || [];
        const userIndex = users.findIndex(u => u.username === user.username);
        if (userIndex !== -1) {
            users[userIndex].language = lang;
            localStorage.setItem('users', JSON.stringify(users));
        }
    } else {
        // Store selected language for pre-login pages
        localStorage.setItem('selectedLanguage', lang);
    }
    // Apply translations after setting language
    if (typeof applyTranslations === 'function') {
        applyTranslations();
    }
}

function t(key) {
    const lang = getUserLanguage();
    return translations[lang][key] || key;
}

// Export for use in other files
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { translations, getUserLanguage, setUserLanguage, t };
}
